-- ============================================================
-- reports.sql — Table des raisons de signalement
-- ------------------------------------------------------------
-- À exécuter UNE FOIS dans le dashboard Supabase :
-- SQL Editor → coller ce fichier → Run.
-- Stocke la raison de chaque signalement (texte libre ou motif).
-- ============================================================

create table if not exists reports (
  id              bigint generated by default as identity primary key,
  post_id         bigint not null,
  reporter_id     text not null,
  reporter_pseudo text,
  reason          text,
  created_at      timestamptz not null default now()
);

-- RLS : lecture/écriture publiques comme le reste du site (clé publique)
alter table reports enable row level security;

drop policy if exists "reports_select_public" on reports;
create policy "reports_select_public" on reports
  for select using (true);

drop policy if exists "reports_insert_public" on reports;
create policy "reports_insert_public" on reports
  for insert with check (true);

-- Index : retrouver rapidement tous les signalements d'un post
create index if not exists reports_post_id_idx on reports (post_id);
